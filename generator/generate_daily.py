def date_seed(date_str):
    return int(hashlib.sha256(date_str.encode("utf-8")).hexdigest(), 16)


def pick(pool, date_str):
    return pool[date_seed(date_str) % len(pool)]


def strip_md(text):
    """去掉 LLM 爱加的 markdown 标记（# * ` 等），返回干净纯文本。"""
    if not text:
        return text
    text = re.sub(r"[#*`>_~]", "", text)
    return re.sub(r"\s+", " ", text).strip()


def norm_plain(p):
    """去掉可能多余的'大白话：'前缀，避免和网页里的标签重复。"""
    if not p:
        return p
    return re.sub(r"^\s*大白话[：:]\s*", "", p).strip()


def try_fetch(url):
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "daily-apk-demo/3.0"})
        with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
            return resp.read().decode("utf-8", errors="ignore")
    except Exception:
        return None


def call_llm(system, user):
    """OpenAI 兼容接口。无密钥或失败返回 None。LLM 只用于写'大白话'，不生成源文。"""
    if not LLM_API_KEY:
        return None
    body = json.dumps({
        "model": LLM_MODEL,
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
        "temperature": 0.8,
    }).encode("utf-8")
    req = urllib.request.Request(
        LLM_BASE_URL.rstrip("/") + "/chat/completions",
        data=body,
        headers={"Authorization": "Bearer " + LLM_API_KEY,
                 "Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        return data["choices"][0]["message"]["content"].strip()
    except Exception:
        return None


# 真实文库索引（marxists.org）。URL 需在目标环境核实；任何失败都回退内置真实库。
MAO_CORPUS_URLS = [
    "https://www.marxists.org/chinese/maozedong/marxist.org-chinese-mao-1930.htm",
    "https://www.marxists.org/chinese/maozedong/marxist.org-chinese-mao-1937.htm",
    "https://www.marxists.org/chinese/maozedong/marxist.org-chinese-mao-1944.htm",
    "https://www.marxists.org/chinese/maozedong/marxist.org-chinese-mao-1945.htm",
]


def fetch_real_mao(date_str):
    """从真实文库按天取一段真实毛选原文。返回 {title, excerpt, source} 或 None。
    注意：只取真实文本，绝不生成。"""
    idx = date_seed(date_str) % len(MAO_CORPUS_URLS)
    html = try_fetch(MAO_CORPUS_URLS[idx])
    if not html:
        return None
    # 极简去标签（无 bs4 依赖）；真实环境建议换成 BeautifulSoup 提取得更干净。
    import re
    text = re.sub(r"<script.*?</script>", " ", html, flags=re.S)
    text = re.sub(r"<style.*?</style>", " ", text, flags=re.S)
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    # 取一段像样长度的中文
    for seg in re.split(r"[。！？\.!?]", text):
        if 20 <= len(seg) <= 120 and any("\u4e00" <= c <= "\u9fff" for c in seg):
            return {"title": "毛选精选（真实文库）", "excerpt": seg + "。",
                    "source": "marxists.org 真实文库"}
    return None


def gen_mao_plain(excerpt):
    """LLM 只为真实毛选段落写大白话。源文已确定，LLM 不改写。"""
    sys_p = "你用通俗易懂的'大白话'解释一段《毛泽东选集》原文，面向普通读者，" \
            "结合今天的生活/工作场景，200字内，不要编造出处。纯文本输出，" \
            "绝对不要使用 ** # * ` 等任何 markdown 符号。"
    r = call_llm(sys_p, "请用大白话解释这段毛选：\n" + excerpt)
    return strip_md(r) if r else None


def gen_psychology(date_str):
    """每天一条新鲜的心理/哲学概念 + 大白话；失败回退精选库。"""
    sys_p = "每天给用户一条心理学或哲学概念。纯文本，绝对不要使用任何 markdown 符号" \
            "（不要出现 ** # * ` 等）。格式严格为：第一行写概念名称；第二行起先一句话解释这个概念；" \
            "然后另起一行以'大白话：'开头写一段结合生活场景的解释（200字内）；最后可写一句出处。" \
            "不要重复常见套话，力求新鲜易懂。"
    raw = call_llm(sys_p, "今天是" + date_str + "，请给一条今天的概念。")
    if not raw:
        return pick(PSYCHOLOGY_POOL, date_str), "offline"
    raw = strip_md(raw)
    # 按'大白话：'把概念与大白话解释拆开，避免引用区也带上'大白话：'
    m = re.search(r"大白话[：:]\s*", raw)
    if m:
        concept = raw[:m.start()].strip()
        plain_text = raw[m.end():].strip()
    else:
        concept = raw.strip()
        plain_text = ""
    title = concept.splitlines()[0][:40] if concept else "今日心理哲学"
    content = concept[:160]
    return {"title": title, "content": content, "plain": plain_text,
            "source": "LLM 实时生成"}, "online"


def generate():
    today = datetime.date.today()
    date_str = today.isoformat()
    print(f"[模式] MODE={MODE}  日期={date_str}")

    # —— 心理哲学 ——
    if MODE == "curated":
        psychology, psy_src = pick(PSYCHOLOGY_POOL, date_str), "offline"
        print(f"[心理哲学] 精选库 -> {psychology['title']}")
    else:
        psychology, psy_src = gen_psychology(date_str)
        print(f"[心理哲学] {'LLM实时' if psy_src=='online' else '回退精选库'} -> {psychology['title']}")

    # —— 毛选（真实文库轮换；LLM 只写大白话）——
    if MODE == "curated":
        mao, mao_src = pick(MAO_POOL, date_str), "offline"
        print(f"[毛选] 精选库 -> {mao['title']}")
    else:
        real = fetch_real_mao(date_str)
        if real:
            plain = gen_mao_plain(real["excerpt"])
            if plain:
                mao = {**real, "plain": plain}
                mao_src = "online"
                print(f"[毛选] 真实文库+LLM大白话 -> {real['excerpt'][:18]}…")
            else:
                # 抓到真实原文但 LLM 没出大白话：回退内置库同种子条目，保证有准确大白话
                mao = pick(MAO_POOL, date_str)
                mao_src = "offline-real"  # 真实文库取到原文，但大白话用内置（同样准确）
                print(f"[毛选] 真实文库取到原文，大白话回退内置 -> {mao['title']}")
        else:
            mao = pick(MAO_POOL, date_str)
            mao_src = "offline"
            print(f"[毛选] 抓取失败，回退真实段落库 -> {mao['title']}")

    overall = "online" if (psy_src == "online" and mao_src == "online") else "offline"
    payload = {
        "date": date_str,
        "generated_at": datetime.datetime.now().isoformat(timespec="seconds"),
        "mode": MODE,
        "source": overall,
        "psychology": {**psychology, "plain": norm_plain(psychology.get("plain", ""))},
        "mao": {**mao, "plain": norm_plain(mao.get("plain", ""))},
        "pools": {"psychology": PSYCHOLOGY_POOL, "mao": MAO_POOL},
    }
    with open(OUTPUT, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
    print(f"写入 {OUTPUT}（source={overall}）。APK 拉取即可见当日两条。")
    return payload


if __name__ == "__main__":
    generate()
